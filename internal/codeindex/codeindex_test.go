func TestEvaluationRecallAtKAndDeterminism(t *testing.T) {
	r := t.TempDir()
	write(t, r, "context.go", "package x\nfunc CompileContext() { /* select memory and sources for model */ }\nfunc EnforceTokenBudget() {}")
	write(t, r, "migration.go", "package x\nfunc MigrateVectorStores() {}")
	write(t, r, "ranking_test.go", "package x\nfunc TestHybridRanking() {}")
	dir := t.TempDir()
	store, err := vector.NewLocalStore(filepath.Join(dir, "vectors.json"), 4)
	require.NoError(t, err)
	idx, err := Open(r, dir, fakeEmbedder{}, store, DefaultOptions())
	require.NoError(t, err)
	_, err = idx.Update(context.Background())
	require.NoError(t, err)
	cases := []struct{ query, symbol string }{{"where is context memory selected for the model", "CompileContext"}, {"how are vector stores migrated", "MigrateVectorStores"}, {"which test covers hybrid ranking", "TestHybridRanking"}}
	hits := 0
	for _, tc := range cases {
		a, err := idx.Search(context.Background(), tc.query, 3)
		require.NoError(t, err)
		b, err := idx.Search(context.Background(), tc.query, 3)
		require.NoError(t, err)
		require.Equal(t, a, b)
		found := false
		for _, r := range a {
			if r.Chunk.Symbol == tc.symbol {
				found = true
			}
		}
		if found {
			hits++
		}
	}
	require.Equal(t, len(cases), hits, "Recall@3 must remain 1.0 for the evaluation fixture")
}

