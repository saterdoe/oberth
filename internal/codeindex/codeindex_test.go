func TestDiscoveryExcludesSecretsBinariesGeneratedAndSymlinks(t *testing.T) {
	r := t.TempDir()
	write(t, r, "src/main.go", "package main\nfunc CompileContext() { }\n")
	write(t, r, ".env", "TOKEN=secret")
	write(t, r, "id_rsa", "secret")
	write(t, r, "dist/a.js", "x")
	writeBytes(t, r, "bad.go", []byte{'a', 0, 'b'})
	write(t, r, "generated.go", "// Code generated by x. DO NOT EDIT.\npackage x")
	write(t, r, "leaked.go", `package x; const token = "ghp_123456789012345678901234"`)
	write(t, r, ".gitignore", "ignored.go\n")
	write(t, r, "ignored.go", "package ignored")
	files, e := Discover(r, DefaultOptions())
	require.NoError(t, e)
	require.Len(t, files, 2)
	require.Equal(t, ".gitignore", files[0].Path)
	require.Equal(t, "src/main.go", files[1].Path)
}
func TestLanguagesAndSymbolChunks(t *testing.T) {
	cases := map[string]string{"a.go": "package a\nfunc CompileContext() {}", "A.java": "class ContextCompiler {\n public void rankSources() {}\n}", "A.cs": "public class ContextCompiler {\n public void RankSources() {}\n}", "a.ts": "export function selectSources() {}", "a.tsx": "export function ContextPanel() { return <div/> }", "a.js": "function selectSources() {}", "a.jsx": "function ContextPanel() { return <div/> }", "a.py": "def compile_context():\n  pass", "README.md": "# Context\ntext", "unknown.zz": "hello\nworld"}
	for path, body := range cases {
		t.Run(path, func(t *testing.T) {
			f := File{Path: path, Language: Language(path), Content: []byte(body), Hash: hash(body)}
			chunks := ChunkFile("repo:x", f, DefaultOptions(), "e")
			require.NotEmpty(t, chunks)
			require.GreaterOrEqual(t, chunks[0].StartLine, 1)
			require.GreaterOrEqual(t, chunks[0].EndLine, chunks[0].StartLine)
			require.NotEmpty(t, chunks[0].ID)
		})
	}
}
