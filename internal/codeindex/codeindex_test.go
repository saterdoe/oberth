func write(t *testing.T, root, path, s string) { t.Helper(); writeBytes(t, root, path, []byte(s)) }
func writeBytes(t *testing.T, root, path string, b []byte) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(path))
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0700))
	require.NoError(t, os.WriteFile(p, b, 0600))
}

type fakeEmbedder struct{}

func (fakeEmbedder) Fingerprint() string { return "test:4" }
func (fakeEmbedder) Dimensions() int     { return 4 }
func (fakeEmbedder) Embed(_ context.Context, s string) ([]float32, error) {
	v := []float32{0, 0, 0, 0}
	for n, b := range []byte(s) {
		v[n%4] += float32(b % 7)
	}
	return v, nil
}
func (f fakeEmbedder) EmbedBatch(ctx context.Context, x []string) ([][]float32, error) {
	v := make([][]float32, len(x))
	for n, s := range x {
		v[n], _ = f.Embed(ctx, s)
	}
	return v, nil
}
