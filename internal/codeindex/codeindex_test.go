func TestIncrementalHybridSearchAndDeletion(t *testing.T) {
	r := t.TempDir()
	write(t, r, "context.go", "package x\n// CompileContext decides which memory sources are sent to the model.\nfunc CompileContext() {}\n")
	write(t, r, "context_test.go", "package x\nfunc TestCompileContext() {}\n")
	e := fakeEmbedder{}
	dir := t.TempDir()
	s, err := vector.NewLocalStore(filepath.Join(dir, "vectors.json"), 4)
	require.NoError(t, err)
	idx, err := Open(r, dir, e, s, DefaultOptions())
	require.NoError(t, err)
	m, err := idx.Update(context.Background())
	require.NoError(t, err)
	require.Equal(t, 2, m.Indexed)
	results, err := idx.Search(context.Background(), "where is memory context sent to the model", 5)
	require.NoError(t, err)
	require.NotEmpty(t, results)
	require.Equal(t, "CompileContext", results[0].Chunk.Symbol)
	m, err = idx.Update(context.Background())
	require.NoError(t, err)
	require.Zero(t, m.Indexed)
	require.NotZero(t, m.Reused)
	write(t, r, "context.go", "package x\nfunc CompileBudget() {}\n")
	m, err = idx.Update(context.Background())
	require.NoError(t, err)
	require.Equal(t, 1, m.Indexed)
	require.NoError(t, os.Remove(filepath.Join(r, "context_test.go")))
	m, err = idx.Update(context.Background())
	require.NoError(t, err)
	require.NotZero(t, m.Deleted)
	results, _ = idx.Search(context.Background(), "TestCompileContext", 10)
	for _, v := range results {
		require.NotEqual(t, "context_test.go", v.Chunk.Path)
	}
}
